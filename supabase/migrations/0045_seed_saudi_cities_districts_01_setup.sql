-- طلب المؤسس: حقلا المدينة/الحي بنماذج العقار/المشروع/العمارة كانا يعتمدان
-- على قائمة صغيرة يُدخلها المؤسس يدويًا عبر console — عبء إدخال يدوي غير
-- عملي لتغطية كل مدن/أحياء السعودية. هذه الهجرة تعبّئ الجدولين من مصدر
-- بيانات رسمي جاهز (نظام العنوان الوطني السعودي — SPL National Address)،
-- علنيّ ومرخّص CC0-1.0 (public domain، بلا أي قيود استخدام تجاري):
-- https://github.com/yasseralsamman/saudi-national-address
--
-- تضيف أيضًا lat/lng لجدولي cities وdistricts (لم تكن موجودة) — تُستخدم
-- لاحقًا لتحريك خريطة LocationPicker تلقائيًا عند اختيار مدينة/حي.
--
-- آمنة على بيانات حية: لا حذف لأي صف موجود. أي مدينة/حي أدخله المؤسس
-- يدويًا من قبل بنفس الاسم العربي تمامًا يبقى كما هو (يُتجاوز تكرار
-- إدخاله)، ويُعبَّأ فقط lat/lng له إن كان فارغًا. الأحياء تُربط بالمدينة
-- الصحيحة عبر مطابقة داخلية دقيقة (لا تعتمد على تطابق الاسم فقط، تفاديًا
-- لالتباس الأسماء المتكررة بين مدن مختلفة — نحو 375 اسم مدينة يتكرر أكثر
-- من مرة في البيانات الرسمية نفسها، لكونها مدنًا/قرى مختلفة فعليًا).
--
-- الحجم: 4581 مدينة و3732 حي — بيانات ضخمة فعليًا، وليس خطأ.
--
-- مقسّمة على 20 ملفًا مرقّمة (بعد فشل تشغيلها كملف واحد ~1 ميجابايت دفعة
-- واحدة في محرر SQL بسوبابيس) — يجب تشغيلها هنا بالترتيب التالي بالضبط،
-- كل ملف دفعة منفصلة، قبل الانتقال للتالي:
--   01_setup                     (هذا الملف)
--   02_cities_part01 .. part10   (إدخال المدن على 10 دفعات)
--   03_districts_setup
--   04_districts_part01 .. part08 (إدخال الأحياء على 8 دفعات)
--   05_finalize                  (الدمج النهائي + تنظيف الجداول المؤقتة)
-- الجداول المؤقتة (_seed_cities/_seed_districts) تبقى بين الدفعات ولا
-- تُحذف إلا في 05_finalize، لذا لا ضرر من التوقف بين دفعة وأخرى واستكمالها
-- لاحقًا، طالما التزمت بالترتيب أعلاه ولم تُشغّل 05_finalize قبل اكتمال كل
-- دفعات المدن والأحياء.
-- =============================================================================

alter table cities add column if not exists lat double precision;
alter table cities add column if not exists lng double precision;

alter table districts add column if not exists lat double precision;
alter table districts add column if not exists lng double precision;

drop table if exists _seed_cities;
create table _seed_cities (
  seed_id uuid primary key,
  name_ar text not null,
  name_en text not null,
  lat double precision,
  lng double precision
);

